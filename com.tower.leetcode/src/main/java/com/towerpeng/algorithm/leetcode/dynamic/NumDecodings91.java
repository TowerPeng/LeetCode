package com.towerpeng.algorithm.leetcode.dynamic;

/**
 * 一条包含字母 A-Z 的消息通过以下映射进行了 编码 ：
 * "1" -> 'A'
 * "2" -> 'B'
 * ...
 * "25" -> 'Y'
 * "26" -> 'Z'
 * 然而，在 解码 已编码的消息时，你意识到有许多不同的方式来解码，因为有些编码被包含在其它编码当中（"2" 和 "5" 与 "25"）。
 * 例如，"11106" 可以映射为：
 * "AAJF" ，将消息分组为 (1, 1, 10, 6)
 * "KJF" ，将消息分组为 (11, 10, 6)
 * 消息不能分组为  (1, 11, 06) ，因为 "06" 不是一个合法编码（只有 "6" 是合法的）。
 * 注意，可能存在无法解码的字符串。
 * 给你一个只含数字的 非空 字符串 s ，请计算并返回 解码 方法的 总数 。如果没有合法的方式解码整个字符串，返回 0。
 * 题目数据保证答案肯定是一个 32 位 的整数。
 * 示例 1：
 * 输入：s = "12"
 * 输出：2
 * 解释：它可以解码为 "AB"（1 2）或者 "L"（12）。
 * 示例 2：
 * 输入：s = "226"
 * 输出：3
 * 解释：它可以解码为 "BZ" (2 26), "VF" (22 6), 或者 "BBF" (2 2 6) 。
 * 示例 3：
 * 输入：s = "06"
 * 输出：0
 * 解释："06" 无法映射到 "F" ，因为存在前导零（"6" 和 "06" 并不等价）。
 *
 * @Author: 彭涛
 * @Date: 2026/3/6 15:03
 */
public class NumDecodings91 {
    public int numDecodings(String s) {
        int n = s.length(); // 获取字符串长度
        char[] ss = s.toCharArray(); // 转换为字符数组，方便访问每个字符
        int [] dp = new int [ss.length]; // 创建 DP 数组，dp[i]表示前 i+1 个字符的解码方法数

        for(int i = 0;i< n;i++){ // 遍历字符串的每个位置
            dp[i] = 0; // 初始化当前位置的方法数为 0
            if(i==0){ // 处理第一个字符
                dp[i] = (ss[i]=='0')?0:1; // 如果第一个字符是'0'则无法解码为 0，否则为 1 种方法
            }else{ // 处理后续字符
                if(ss[i]!='0'){ // 当前字符不是'0'，可以单独解码
                    dp[i] +=dp[i-1]; // 累加前一个位置的解码方法数（单独解码当前位）
                }
                if(ss[i - 1] == '1' || ss[i - 1] == '2'){ // 前一个字符是'1'或'2'，可能与当前字符组合
                    int val = (ss[i-1]-'0') * 10 + ss[i] - '0'; // 计算两位数字的值
                    if(val<=26){ // 组合值不超过 26，可以解码为字母
                        if(i==1){ // 如果是第二个字符
                            dp[i]++; // 直接加 1（两种情况：单独解码或组合解码）
                        }else{ // 不是第二个字符
                            dp[i] +=dp[i-2]; // 累加前两个位置的解码方法数（组合解码）
                        }
                    }
                }
            }
        }
        return dp[n-1]; // 返回整个字符串的解码方法数
    }

}
